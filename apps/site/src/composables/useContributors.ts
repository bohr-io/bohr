import type { AvatarWallPerson } from '@bohr/ui';
import { onBeforeUnmount, onMounted, type Ref, ref } from 'vue';
import { CONTRIBUTORS_API_URL } from '../config';
import v1Contributors from '../data/v1-contributors.json';

/** Someone who contributed to bohr: a GitHub login and how many commits. */
export interface Contributor {
  login: string;
  avatarUrl: string;
  href: string;
  contributions: number;
}

interface GithubContributor {
  login: string;
  avatar_url: string;
  html_url: string;
  contributions?: number;
  type?: string;
}

const MAX_CONTRIBUTORS = 60;

/**
 * bohr v1's contributors, from its repositories (most of them private, like bohr-io/core): generated by
 * scripts/v1-contributors.mjs, since the browser cannot read them from GitHub.
 */
export const V1_CONTRIBUTORS: Contributor[] = v1Contributors;

function isContributor(value: unknown): value is GithubContributor {
  if (typeof value !== 'object' || value === null) return false;
  const { login, avatar_url: avatar, html_url: profile } = value as Record<string, unknown>;
  return (
    typeof login === 'string' &&
    typeof avatar === 'string' &&
    avatar.startsWith('https://') &&
    typeof profile === 'string' &&
    profile.startsWith('https://github.com/')
  );
}

/** Parses the GitHub contributors API response, dropping bots and anything malformed. */
export function parseContributors(data: unknown): Contributor[] {
  if (!Array.isArray(data)) return [];
  return data
    .filter(isContributor)
    .filter((contributor) => contributor.type !== 'Bot' && !contributor.login.endsWith('[bot]'))
    .map((contributor) => ({
      login: contributor.login,
      avatarUrl: contributor.avatar_url,
      href: contributor.html_url,
      contributions: typeof contributor.contributions === 'number' ? contributor.contributions : 0,
    }));
}

/** One entry per person (GitHub logins ignore case), their contributions added up, the most active first. */
export function mergeContributors(...lists: Contributor[][]): Contributor[] {
  const people = new Map<string, Contributor>();
  for (const contributor of lists.flat()) {
    const key = contributor.login.toLowerCase();
    const known = people.get(key);
    people.set(
      key,
      known === undefined
        ? { ...contributor }
        : { ...known, contributions: known.contributions + contributor.contributions },
    );
  }
  return [...people.values()].sort((a, b) => b.contributions - a.contributions);
}

/** The avatar wall's people, at most MAX_CONTRIBUTORS of them. */
export function toPeople(contributors: Contributor[]): AvatarWallPerson[] {
  return contributors.slice(0, MAX_CONTRIBUTORS).map((contributor) => ({
    name: contributor.login,
    avatarUrl: `${contributor.avatarUrl}${contributor.avatarUrl.includes('?') ? '&' : '?'}s=128`,
    href: contributor.href,
  }));
}

/**
 * bohr's contributors: v1's (in the page from the build on) and bohr-io/bohr's, fetched in the browser after mount.
 * On any error (the repository may still be private) the wall keeps v1's.
 */
export function useContributors(): Ref<AvatarWallPerson[]> {
  const people = ref<AvatarWallPerson[]>(toPeople(mergeContributors(V1_CONTRIBUTORS)));
  const controller = typeof AbortController === 'function' ? new AbortController() : undefined;

  onMounted(async () => {
    try {
      const response = await fetch(`${CONTRIBUTORS_API_URL}?per_page=100`, {
        headers: { Accept: 'application/vnd.github+json' },
        signal: controller?.signal,
      });
      if (!response.ok || response.status === 204) return;
      const live = parseContributors(await response.json());
      if (live.length > 0) people.value = toPeople(mergeContributors(V1_CONTRIBUTORS, live));
    } catch {
      // v1's stay
    }
  });

  onBeforeUnmount(() => controller?.abort());

  return people;
}
