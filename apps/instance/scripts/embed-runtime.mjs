// Bundles runtime/project-worker and writes it into src/generated/runtime.ts, so the instance can
// upload the project Worker to the accounts it provisions. Runs before build, typecheck and test.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const workerPackage = path.dirname(require.resolve('@bohr/project-worker/package.json'));
const { version } = JSON.parse(readFileSync(path.join(workerPackage, 'package.json'), 'utf8'));
// The agent image has its own version: a release that only changes the project Worker needs no new image
const agentImageVersion = JSON.parse(
  readFileSync(path.join(here, '../../../runtime/agent/package.json'), 'utf8'),
).version;

const result = await build({
  entryPoints: [path.join(workerPackage, 'src/index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2023',
  mainFields: ['module', 'main'],
  conditions: ['workerd', 'worker', 'browser'],
  external: ['cloudflare:*', 'node:*', 'crypto'],
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
});
const source = result.outputFiles[0].text;

const out = path.join(here, '../src/generated/runtime.ts');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/embed-runtime.mjs from runtime/project-worker. Do not edit.\n` +
    `export const PROJECT_WORKER_VERSION = ${JSON.stringify(version)};\n` +
    `export const AGENT_IMAGE_VERSION = ${JSON.stringify(agentImageVersion)};\n` +
    `export const PROJECT_WORKER_SOURCE: string = ${JSON.stringify(source)};\n`,
);
console.log(`src/generated/runtime.ts: project Worker ${version}, ${Math.round(source.length / 1024)} KiB`);

// The instance's own version, for the User-Agent of its API calls and the telemetry ping
const instanceVersion = JSON.parse(readFileSync(path.join(here, '../package.json'), 'utf8')).version;
writeFileSync(
  path.join(here, '../src/generated/version.ts'),
  `// Generated by scripts/embed-runtime.mjs from package.json. Do not edit.
` +
    `export const BOHR_VERSION = ${JSON.stringify(instanceVersion)};
`,
);

// The D1 migrations, so the instance can apply them itself (lib/migrate.ts) when it was deployed without
// `wrangler d1 migrations apply`, e.g. by the Deploy to Cloudflare button or a plain `wrangler deploy`.
const migrationsDir = path.join(here, '../migrations');
const migrations = readdirSync(migrationsDir)
  .filter((name) => name.endsWith('.sql'))
  .sort()
  .map((name) => ({
    name,
    statements: readFileSync(path.join(migrationsDir, name), 'utf8')
      .split('--> statement-breakpoint')
      .map((statement) => statement.trim())
      .filter((statement) => statement.length > 0),
  }));
writeFileSync(
  path.join(here, '../src/generated/migrations.ts'),
  `// Generated by scripts/embed-runtime.mjs from migrations/. Do not edit.\n` +
    `export const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`src/generated/migrations.ts: ${migrations.length} migrations`);
