    expect((await db.select().from(projects).where(eq(projects.id, 'p_loja')).get())?.mode).toBe('byo');
    expect(bohr.scripts.has('p_loja-main')).toBe(false);
    expect(await db.select().from(hostnames).all()).toEqual([]);

