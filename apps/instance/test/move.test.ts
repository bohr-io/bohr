async function savePlan(plan: Partial<typeof buildPlans.$inferInsert> = {}) {
  await db
    .insert(buildPlans)
    .values({
      projectId: 'p_loja',
      nodeVersion: '20',
      install: 'npm ci',
      build: "export CI='false'; npm run build",
      files: { 'wrangler.jsonc': PLAN_WRANGLER, '.bohr/worker.mjs': 'export default {};\n' },
      ...plan,
    })
    .run();
}

const prepare = (headers: Record<string, string>, connectionId: string) =>
  call('/api/projects/p_loja/move', { method: 'POST', headers, body: JSON.stringify({ connectionId }) });

describe('moving a repository that still deploys with bohr v1 workflow and the build plan', () => {
  it('writes deploy.json and the plan files, replaces bohr.yml with the deploy to the owner account', async () => {
    const { headers, connectionId } = await migratedProject();
    customer.files = new Map([
      ['.github/workflows/bohr.yml', V1_WORKFLOW],
      ['.github/workflows/bohr-dev.yml', V1_WORKFLOW],
      ['.github/workflows/ci.yml', 'name: CI\non: [pull_request]\n'],
      ['package.json', '{"scripts":{"build":"vite build"}}'],
    ]);
    await savePlan();

    const prepared = await prepare(headers, connectionId);
    expect(prepared.status).toBe(200);
    expect(((await prepared.json()) as { move: unknown }).move).toMatchObject({ status: 'prepared', script: 'loja' });
    // bohr v1's workflows leave first, so the branch's later commits no longer deploy to bohr's hosting
    expect(customer.commits).toEqual([
      'delete .github/workflows/bohr.yml',
      'delete .github/workflows/bohr-dev.yml',
      'put .github/workflows/bohr-deploy.yml',
      'put .bohr/deploy.json',
      'put wrangler.jsonc',
      'put .bohr/worker.mjs',
    ]);
    expect(JSON.parse(customer.branchFiles.get('.bohr/deploy.json') ?? '')).toEqual({
      node: '20',
      install: 'npm ci',
      build: "export CI='false'; npm run build",
    });
    expect(customer.branchFiles.get('.bohr/worker.mjs')).toBe('export default {};\n');
    const wrangler = customer.branchFiles.get('wrangler.jsonc') ?? '';
    expect(wrangler.startsWith('// Generated by the bohr v2 migration')).toBe(true);
    expect(JSON.parse(stripJsonComments(wrangler))).toMatchObject({
      name: 'loja',
      main: '.bohr/worker.mjs',
      vars: { PUBLIC_API: 'https://api.example.com' },
    });
    const workflow = customer.branchFiles.get('.github/workflows/bohr-deploy.yml') ?? '';
    expect(workflow.startsWith(DEPLOY_WORKFLOW_HEADER)).toBe(true);
    expect(workflow).toContain('branches: ["main"]');
    expect(workflow).toContain(`run: "export CI='false'; npm run build"`);
    expect(workflow).toContain('node-version: "20"');
    // wrangler needs a newer Node.js than the build's
    expect(workflow).toContain('node-version: "22"');
    expect(workflow).toContain('npx wrangler deploy --config "$gate"');
    expect(usesDeployCredentials(workflow)).toBe(true);
    expect(workflow).not.toContain('D1 migrations');

    // The merged workflow gets the credentials of the account chosen for the move, before and after it completes
    expect((await deployCredentials(db, cloud, PRODUCTION_RUN)).accountId).toBe('acc-user');

    // Preparing again starts the branch over and keeps the pull request
    customer.commits = [];
    customer.branches.set('bohr/move-to-cloudflare', 'sha-old');
    expect((await prepare(headers, connectionId)).status).toBe(200);
    expect(customer.branches.get('bohr/move-to-cloudflare')).toBe('sha-main');
    expect(customer.commits).toHaveLength(6);
    expect(customer.pulls).toHaveLength(1);

    if (customer.pulls[0]) customer.pulls[0].merged = true;
    world.scripts.set('loja', { metadata: {}, modules: [] });
    customer.zones.set('other.com', 'zone-user-other');
    const done = (await (await call('/api/projects/p_loja/move/complete', { method: 'POST', headers })).json()) as {
      move: { status: string };
    };
    expect(done.move.status).toBe('done');
    // Nothing deploys the project to bohr's hosting any more
    expect(await db.select().from(buildPlans).all()).toEqual([]);
    expect((await deployCredentials(db, cloud, PRODUCTION_RUN)).accountId).toBe('acc-user');
  });

  it('refuses a repository with nothing to describe its build, or a plan deploy.json cannot hold', async () => {
    const { headers, connectionId } = await migratedProject();
    customer.files = new Map([['.github/workflows/bohr.yml', V1_WORKFLOW]]);
    const none = await prepare(headers, connectionId);
    expect(none.status).toBe(409);
    expect(await none.text()).toContain('.bohr/deploy.json');

    await savePlan({ build: 'npm run build\nnpm run export' });
    const multiline = await prepare(headers, connectionId);
    expect(multiline.status).toBe(409);
    expect(await multiline.text()).toContain("bohr's build plan");
    expect(customer.commits).toEqual([]);
    expect(customer.pulls).toEqual([]);
  });
});

describe('moving a repository the bohr agent prepared', () => {
  it('rewrites the workflow bohr wrote for its hosting, keeps deploy.json and removes bohr.yml', async () => {
    const { headers, connectionId } = await migratedProject();
    const deployJson =
      '{ "directory": "site", "packageManager": "pnpm", "install": "pnpm i", "build": "pnpm build" }\n';
    customer.files = new Map([
      ['.github/workflows/bohr.yml', V1_WORKFLOW],
      [
        '.github/workflows/bohr-deploy.yml',
        renderDeployWorkflow(deployConfigSchema.parse(JSON.parse(deployJson)), {
          productionBranch: 'main',
          target: 'bohr-cloud',
        }),
      ],
      ['.bohr/deploy.json', deployJson],
      [
        'site/wrangler.jsonc',
        '{ "compatibility_date": "2026-08-15", "d1_databases": [{ "binding": "DB", "database_name": "loja", "database_id": "x", "migrations_dir": "migrations" }] }\n',
      ],
    ]);
    // The plan bohr.yml deployed with: its files the repository lacks join it, the others stay as they are
    await savePlan({ files: { 'site/wrangler.jsonc': PLAN_WRANGLER, '.bohr/worker.mjs': 'export default {};\n' } });

    const prepared = await prepare(headers, connectionId);
    expect(prepared.status).toBe(200);
    // No "name" in the config: the Worker takes the project's slug
    expect(((await prepared.json()) as { move: unknown }).move).toMatchObject({ script: 'loja' });
    expect(customer.commits).toEqual([
      'delete .github/workflows/bohr.yml',
      'put .github/workflows/bohr-deploy.yml',
      'put .bohr/worker.mjs',
      'put site/wrangler.jsonc',
    ]);
    const wrangler = JSON.parse(stripJsonComments(customer.branchFiles.get('site/wrangler.jsonc') ?? '')) as {
      name: string;
      vars: unknown;
      d1_databases: unknown[];
    };
    expect(wrangler).toMatchObject({ name: 'loja', vars: { PUBLIC_API: 'https://api.example.com' } });
    expect(wrangler.d1_databases).toHaveLength(1);
    const workflow = customer.branchFiles.get('.github/workflows/bohr-deploy.yml') ?? '';
    expect(workflow).toContain('working-directory: "site"');
    expect(workflow).toContain('corepack enable');
    expect(workflow).toContain('name: D1 migrations');
    expect(usesDeployCredentials(workflow)).toBe(true);
  });

  it('writes the deploy workflow when the agent wrote none', async () => {
    const { headers, connectionId } = await migratedProject();
    customer.files = new Map([
      ['.bohr/deploy.json', '{ "build": "npm run build" }\n'],
      ['wrangler.jsonc', MIGRATED_WRANGLER],
    ]);
    expect((await prepare(headers, connectionId)).status).toBe(200);
    expect(customer.commits).toEqual(['put .github/workflows/bohr-deploy.yml', 'put wrangler.jsonc']);
    expect(customer.branchFiles.get('.github/workflows/bohr-deploy.yml')?.startsWith(DEPLOY_WORKFLOW_HEADER)).toBe(
      true,
    );
  });
});

