type Pull = { number: number; head: string; base: string; title: string; merged: boolean };

/** The customer's repository and Cloudflare account, as far as the move touches them. */
class Customer {
  files = new Map<string, string>([
    ['.github/workflows/bohr-deploy.yml', MIGRATED_WORKFLOW],
    ['wrangler.jsonc', MIGRATED_WRANGLER],
  ]);
  branchFiles = new Map<string, string>();
  /** The move branch's commits, in order: "put <path>" or "delete <path>". */
  commits: string[] = [];
  branches = new Map<string, string>([['main', 'sha-main']]);
  pulls: Pull[] = [];
  zones = new Map<string, string>([['example.com', 'zone-user-example']]);
  /** Zones added to the account whose nameservers do not point at Cloudflare yet. */
  pendingZones = new Set<string>();
  domains: { hostname: string; service: string; zone_id: string }[] = [];
  /** Hostnames with DNS records already: Cloudflare refuses a Custom Domain over them. */
  dnsRecords = new Set<string>();

  async handle(request: Request): Promise<Response | null> {
    const url = new URL(request.url);
    const body = request.method === 'GET' ? '' : await request.clone().text();
    if (url.hostname === 'api.cloudflare.com') {
      const path = url.pathname.replace('/client/v4', '');
      if (path === '/zones') {
        const id = this.zones.get(url.searchParams.get('name') ?? '');
        return Response.json({
          success: true,
          errors: [],
          result: id
            ? [{ id, name: url.searchParams.get('name'), status: this.pendingZones.has(id) ? 'pending' : 'active' }]
            : [],
        });
      }
      // A token from bohr's template has no Workers Routes permission
      if (/^\/zones\/[^/]+\/workers\/routes/.test(path)) {
        return Response.json(
          { success: false, errors: [{ code: 10000, message: 'Authentication error' }], result: null },
          { status: 403 },
        );
      }
      if (path === '/accounts/acc-user/workers/domains' && request.method === 'PUT') {
        const domain = JSON.parse(body) as { hostname: string; service: string; zone_id: string };
        if (this.dnsRecords.has(domain.hostname)) {
          return Response.json(
            {
              success: false,
              errors: [
                { code: 100117, message: 'Hostname already has externally managed DNS records (A, CNAME, etc).' },
              ],
              result: null,
            },
            { status: 409 },
          );
        }
        this.domains.push(domain);
        return Response.json({ success: true, errors: [], result: { id: 'dom' } });
      }
      return null;
    }
    if (url.hostname !== 'api.github.com') return null;
    const repo = '/repos/ana/loja';
    const contents = new RegExp(`^${repo}/contents/(.+)$`).exec(url.pathname);
    if (contents?.[1] !== undefined) {
      const path = decodeURIComponent(contents[1]);
      if (request.method === 'GET') {
        const text = this.files.get(path);
        const entries = [...this.files.keys()].filter((file) => file.startsWith(`${path}/`));
        if (text === undefined && entries.length > 0) {
          return Response.json(
            entries.map((file) => ({
              type: 'file',
              name: file.slice(path.length + 1),
              path: file,
              sha: `blob-${file}`,
            })),
          );
        }
        if (text === undefined) return Response.json({ message: 'Not Found' }, { status: 404 });
        return Response.json({
          type: 'file',
          sha: `blob-${path}`,
          encoding: 'base64',
          content: btoa(unescape(encodeURIComponent(text))),
        });
      }
      if (request.method === 'DELETE') {
        this.commits.push(`delete ${path}`);
        return Response.json({ commit: { sha: `commit-delete-${path}` } }, { status: 200 });
      }
      const put = JSON.parse(body) as { content: string; branch: string };
      this.commits.push(`put ${path}`);
      this.branchFiles.set(path, decodeURIComponent(escape(atob(put.content))));
      return Response.json({ commit: { sha: `commit-${path}` } }, { status: 200 });
    }
    const ref = new RegExp(`^${repo}/git/refs?/heads/(.+)$`).exec(url.pathname);
    if (ref?.[1] !== undefined) {
      const branch = decodeURIComponent(ref[1]);
      if (request.method === 'GET') {
        const sha = this.branches.get(branch);
        return sha === undefined
          ? Response.json({ message: 'Not Found' }, { status: 404 })
          : Response.json({ object: { sha } });
      }
      this.branches.set(branch, (JSON.parse(body) as { sha: string }).sha);
      return Response.json({ object: { sha: 'x' } });
    }
    if (url.pathname === `${repo}/git/refs` && request.method === 'POST') {
      const { ref: name, sha } = JSON.parse(body) as { ref: string; sha: string };
      this.branches.set(name.replace('refs/heads/', ''), sha);
      return Response.json({ ref: name }, { status: 201 });
    }
    const pullJson = (pull: Pull) => ({
      number: pull.number,
      node_id: `PR_${pull.number}`,
      html_url: `https://github.com/ana/loja/pull/${pull.number}`,
      state: pull.merged ? 'closed' : 'open',
      merged: pull.merged,
      head: { ref: pull.head, sha: 'head' },
      base: { ref: pull.base },
      title: pull.title,
    });
    if (url.pathname === `${repo}/pulls` && request.method === 'GET') {
      return Response.json(this.pulls.filter((pull) => !pull.merged).map(pullJson));
    }
    if (url.pathname === `${repo}/pulls` && request.method === 'POST') {
      const input = JSON.parse(body) as { head: string; base: string; title: string };
      const pull = { number: 7 + this.pulls.length, ...input, merged: false };
      this.pulls.push(pull);
      return Response.json(pullJson(pull), { status: 201 });
    }
    const one = new RegExp(`^${repo}/pulls/(\\d+)$`).exec(url.pathname);
    if (one?.[1] !== undefined) {
      const pull = this.pulls.find((candidate) => candidate.number === Number(one[1]));
      return pull === undefined
        ? Response.json({ message: 'Not Found' }, { status: 404 })
        : Response.json(pullJson(pull));
    }
    return null;
  }
}

