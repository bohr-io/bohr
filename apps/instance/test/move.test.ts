    expect(customer.commits).toEqual([
      'put .github/workflows/bohr-deploy.yml',
      'put wrangler.jsonc',
      'put .assetsignore',
    ]);
    const ignore = (customer.branchFiles.get('.assetsignore') ?? '').split('\n');
    for (const pattern of [
      '.git',
      '.env*',
      'node_modules',
      '.github',
      '.bohr',
      'wrangler.json*',
      '/api/',
      'package.json',
    ]) {
      expect(ignore, pattern).toContain(pattern);
    }

    customer.commits = [];
