function pickLanguage() {
  for (const tag of navigator.languages?.length ? navigator.languages : [navigator.language ?? '']) {
    const code = String(tag).toLowerCase();
    if (code.startsWith('pt')) return 'pt-BR';
    if (code.startsWith('es')) return 'es';
    if (code.startsWith('en')) return 'en';
  }
  return 'pt-BR';
}

export const lang = pickLanguage();

/** The text of `key` in the visitor's language, with {name} placeholders filled from `vars`. */
export function t(key, vars = {}) {
  const text = strings[lang][key] ?? strings['pt-BR'][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** Fills data-i18n (text), data-i18n-placeholder, data-i18n-label (aria-label) and data-i18n-title. */
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  }
  for (const element of root.querySelectorAll('[data-i18n-label]')) {
    element.setAttribute('aria-label', t(element.dataset.i18nLabel));
  }
  for (const element of root.querySelectorAll('[data-i18n-title]')) element.title = t(element.dataset.i18nTitle);
}
