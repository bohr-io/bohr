const MESSAGES: Record<Locale, Messages> = { 'pt-BR': ptBR, en, es };

export function t(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}): string {
  return MESSAGES[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

export function formatCost(locale: Locale, usd: number): string {
  const formatted = new Intl.NumberFormat(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(usd);
  return `US$ ${formatted}`;
}

